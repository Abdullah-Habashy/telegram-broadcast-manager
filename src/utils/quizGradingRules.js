// أي مخرج مش مطابق بيتعامل على إنه فشل صريح مش صفر — الفرق مهم: الصفر بيتحسب في درجة
// الطالب، والفشل بيتعلّم عشان الموظف يصحّح السؤال ده بإيده
function normalizeGrade(raw) {
  if (!raw || typeof raw !== 'object') return null;
  const verdict = ['correct', 'partial', 'incorrect'].includes(raw.verdict) ? raw.verdict : null;
  if (!verdict) return null;
  let ratio = Number(raw.score_ratio);
  if (!Number.isFinite(ratio)) ratio = verdict === 'correct' ? 1 : 0;
  // النموذج ساعات بيقول correct وبيحط 0.9، أو incorrect وبيحط 0.2. الحكم هو اللي بيكسب
  // في الطرفين — الدرجة الجزئية ليها معنى في partial بس
  if (verdict === 'correct') ratio = 1;
  if (verdict === 'incorrect') ratio = 0;
  return {
    verdict,
    score_ratio: Math.max(0, Math.min(1, ratio)),
    reason: typeof raw.reason === 'string' ? raw.reason.trim() : '',
  };
}

// الفرع بيتبعت مع رأسه: "رأس السؤال\nأ) نص الفرع". من غير الرأس، فرع زي "اذكر اتنين
// منهم" بيوصل النموذج بلا سياق والحكم بيبقى عشوائي
function questionTextForGrading(question) {
  if (!question.parent_text) return question.text;
  const label = question.label ? `${question.label}) ` : '';
  return `${question.parent_text}\n\n${label}${question.text}`;
}

// نص رسالة المستخدم — الفرق بين إجابة مكتوبة وإجابة مصوّرة
function buildUserText({ studentAnswer, hasImage = false }) {
  // **التعليمة بتتغيّر مع الصورة.** من غيرها النموذج بيوصف الصورة أو يعلّق على الخط
  // بدل ما يصحّح، والطالب بياخد "خطك مش واضح" مكان درجته
  const userText = hasImage
    ? 'إجابة الطالب في الصورة دي — إجابة مكتوبة بخط إيده على ورق.\n\n'
      + 'اقرا اللي مكتوب فيها وصحّحه بنفس القواعد فوق بالظبط. **الخط والتنسيق وشكل الورقة'
      + ' مش محسوبين عليه خالص** — زي الإملاء بالظبط. لو فيه كلمة مش واضحة، خد أقرب قراءة'
      + ' معقولة ليها في سياق السؤال بدل ما تحسبها ناقصة.'
      + ' ودي قاعدة تصحيح ليك إنت — متذكرهاش للطالب في الـ reason.'
      + (String(studentAnswer || '').trim() ? `\n\nوكتب معاها:\n${studentAnswer}` : '')
    : `إجابة الطالب:\n${studentAnswer}`;
  return userText;
}

